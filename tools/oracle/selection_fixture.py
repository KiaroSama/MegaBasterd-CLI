"""Offline Unicode14/fnmatch oracle; run isolated with the retained Python3.11.9."""

import argparse
from datetime import datetime, timezone
import hashlib
import itertools
import json
import logging
from pathlib import Path
import sys
import unicodedata
import uuid

sys.dont_write_bytecode = True


def exact(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        if path.read_bytes() != content:
            raise ValueError("Existing selection oracle output differs; original preserved")
    else:
        with path.open("xb") as stream:
            stream.write(content)


def generate(root):
    import fnmatch

    if sys.version.split()[0] != "3.11.9" or unicodedata.unidata_version != "14.0.0":
        raise ValueError("Selection oracle requires retained Python3.11.9/Unicode14.0.0")
    folded = [(chr(code), chr(code).casefold()) for code in range(0x110000)
              if not 0xD800 <= code <= 0xDFFF and chr(code).casefold() != chr(code)]
    def literal(value):
        return '"' + ''.join(f"\\u{{{ord(c):x}}}" for c in value) + '"'
    entries = [f"('\\u{{{ord(char):x}}}', {literal(value)})" for char, value in folded]
    lines = ["// Generated by tools/oracle/selection_fixture.py from Python3.11.9 Unicode14.",
             "// Unicode data notice: licenses/Unicode-3.0.txt. Do not regenerate with another Unicode version.",
             "", "#[rustfmt::skip]", f"const FOLD: [(char, &str); {len(folded)}] = ["]
    lines.extend("    " + ", ".join(entries[i:i+4]) + "," for i in range(0, len(entries), 4))
    lines.extend([
        "];", "", "pub(super) fn casefold(text: &str) -> String {",
        "    let mut output = String::with_capacity(text.len());",
        "    for character in text.chars() {",
        "        match FOLD.binary_search_by_key(&character, |entry| entry.0) {",
        "            Ok(index) => output.push_str(FOLD[index].1),",
        "            Err(_) => output.push(character),", "        }", "    }", "    output", "}",
    ])
    table = ("\n".join(lines) + "\n").encode("utf-8")
    # The fixture calls stdlib fnmatchcase after the source's explicit separator/full-fold normalization.
    patterns = {"*", "?", "??", "**/e1.mkv", "a**b", "{a,b}.mkv", "[ab].txt",
                "[!ab].txt", "[^a].txt", "[abc", "[]", "[!]", "[]]", "[!]]",
                "Straße.*", "STRASSE.*", "?ş.*", "σ.*", "İ.*", "ffi.*", "𐐀.*"}
    for length in range(1, 5):
        patterns.update("[" + "".join(chars) + "]"
                        for chars in itertools.product("ab-!", repeat=length))
    subjects = ["", "a", "b", "c", "-", "!", "[", "]", "^", "ab", "a/b", "a\nb",
                "a.mkv", "b.mkv", "{a,b}.mkv", "a.txt", "b.txt", "c.txt", "[abc", "[]", "[!]",
                "e1.mkv", "Show/e1.mkv", "Straße.mkv", "STRASSE.MKV", "Öş.mkv", "Σ.mkv",
                "ς.mkv", "İ.mkv", "i̇.mkv", "ﬃ.mkv", "𐐨.mkv"]
    cases = [{"pattern": pattern, "matches": [index for index, subject in enumerate(subjects)
              if fnmatch.fnmatchcase(subject.casefold(), pattern.replace("\\", "/").casefold())]}
             for pattern in sorted(patterns)]
    document = {"python": "3.11.9", "unicode": "14.0.0", "fold_mappings": len(folded),
                "fold_table_sha256": hashlib.sha256(table).hexdigest(), "subjects": subjects, "cases": cases}
    fixture = [json.dumps({key: value for key, value in document.items() if key != "cases"},
                         ensure_ascii=True, separators=(",", ":"))[:-1] + ',"cases":[']
    fixture.extend(json.dumps(case, ensure_ascii=True, separators=(",", ":")) +
                   ("," if index < len(cases)-1 else "") for index, case in enumerate(cases))
    fixture.append("]}")
    exact(root / "src/transfers/unicode_fold.rs", table)
    exact(root / "tests/fixtures/selection/filter-oracle.json", ("\n".join(fixture)+"\n").encode("utf-8"))
    logging.info("Generated source-only fold_mappings=%d patterns=%d subjects=%d", len(folded), len(cases), len(subjects))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project-root", type=Path, required=True)
    args = parser.parse_args()
    root = args.project_root.resolve()
    handler = None
    try:
        directory = root / "Logs/oracle"
        directory.mkdir(parents=True, exist_ok=True)
        stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d_%H-%M-%S_UTC")
        handler = logging.FileHandler(directory / f"selection_fixture_{stamp}_{uuid.uuid4().hex}.log",
                                      mode="x", encoding="utf-8")
        logging.basicConfig(level=logging.INFO, handlers=[handler],
                            format="[%(asctime)s UTC] [%(levelname)s] [ORACLE] %(message)s",
                            datefmt="%Y-%m-%d %H:%M:%S")
        import time
        handler.formatter.converter = time.gmtime
    except OSError:
        logging.basicConfig(level=logging.INFO, stream=sys.stderr,
                            format="[%(levelname)s] [ORACLE] %(message)s")
        print("Selection oracle logging unavailable; using console only", file=sys.stderr)
    try:
        logging.info("Selection source-oracle started")
        generate(root)
        logging.info("Selection source-oracle finished exit=0")
        return 0
    except (OSError, ValueError, ImportError):
        logging.exception("Selection source-oracle failed; original outputs preserved exit=1")
        return 1
    finally:
        logging.shutdown()
        if handler is not None:
            handler.close()


if __name__ == "__main__":
    raise SystemExit(main())
